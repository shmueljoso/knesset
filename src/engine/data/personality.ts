export function greeting(att: number): string {
  if (att >= 60) return 'אחי/אחותי! מה צריך?';
  if (att >= 25) return 'שמח לראות אותך.';
  if (att > -15) return 'כן? במה אפשר לעזור?';
  if (att > -50) return 'אה. זה את/ה.';
  return 'אין לי מה להגיד לך.';
}
