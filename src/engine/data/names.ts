export function makeName(rnd: () => number, pool: NamePoolId, gender: Gender, used: Set<string>): string {
  const p = NAME_POOLS[pool];
  for (let i = 0; i < 40; i++) {
    const first = (gender === 'm' ? p.m : p.f)[Math.floor(rnd() * (gender === 'm' ? p.m.length : p.f.length))];
    const last = p.last[Math.floor(rnd() * p.last.length)];
    const n = `${first} ${last}`;
    if (!used.has(n)) {
      used.add(n);
      return n;
    }
  }
  const fallback = `${p.m[0]} ${p.last[0]} ${used.size}`;
  used.add(fallback);
  return fallback;
}

/** שמות פרטיים נשיים נפוצים (לזיהוי מגדר של שמות אמיתיים מקובצי תרחיש) */
